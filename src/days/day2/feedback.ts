const BY_COMBINATION: Record<string, number> = { PVC: 1, PV: 2, PC: 3, P: 4, V: 5, C: 6, VC: 7, "": 12 }

// Fat only changes the state when it comes with a single component (or alone);
// otherwise the protein/vegetables/carbs combination decides.
export function getDay2Feedback({ protein, vegetables, carbs, fat }: Day2Data): Day2Feedback {
  const key = `${protein ? "P" : ""}${vegetables ? "V" : ""}${carbs ? "C" : ""}`

  if (fat) {
    if (key === "C") return FEEDBACK[8]
    if (key === "P") return FEEDBACK[9]
    if (key === "V") return FEEDBACK[10]
    if (key === "") return FEEDBACK[11]
  }

  return FEEDBACK[BY_COMBINATION[key]]
}
